USE DATABASE FRAUD_DB;
USE SCHEMA PUBLIC;

CREATE OR REPLACE VIEW FRAUD_TRAINING_VIEW AS
SELECT
    STEP,
    TYPE,
    AMOUNT,
    OLD_BALANCE_ORIG,
    NEW_BALANCE_ORIG,
    OLD_BALANCE_DEST,
    NEW_BALANCE_DEST,
    ISFRAUD
FROM FRAUD_SPLIT
WHERE DATASPLIT = 'TRAIN';

CREATE OR REPLACE SNOWFLAKE.ML.CLASSIFICATION FRAUD_MODEL
(
    INPUT_DATA => SYSTEM$REFERENCE(
        'VIEW',
        'FRAUD_DB.PUBLIC.FRAUD_TRAINING_VIEW'
    ),
    TARGET_COLNAME => 'ISFRAUD',
    CONFIG_OBJECT => {'evaluate': TRUE}
);
