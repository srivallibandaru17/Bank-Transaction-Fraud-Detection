USE DATABASE FRAUD_DB;
USE SCHEMA PUBLIC;

CREATE OR REPLACE TABLE FRAUD_FEATURES AS
SELECT
    STEP,
    TYPE,
    TRY_TO_DOUBLE(AMOUNT) AS AMOUNT,
    TRY_TO_DOUBLE(OLD_BALANCE_ORIG) AS OLD_BALANCE_ORIG,
    TRY_TO_DOUBLE(NEW_BALANCE_ORIG) AS NEW_BALANCE_ORIG,
    TRY_TO_DOUBLE(OLD_BALANCE_DEST) AS OLD_BALANCE_DEST,
    TRY_TO_DOUBLE(NEW_BALANCE_DEST) AS NEW_BALANCE_DEST,
    ISFRAUD,
    ISFLAGGEDFRAUD
FROM FRAUD_DATA;
