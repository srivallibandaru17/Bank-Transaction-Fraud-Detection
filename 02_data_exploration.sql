USE DATABASE FRAUD_DB;
USE SCHEMA PUBLIC;

-- 1. Check total transactions
SELECT COUNT(*) AS TOTAL_TRANSACTIONS
FROM FRAUD_DATA;

-- 2. Check fraud and non-fraud transactions
SELECT
    ISFRAUD,
    COUNT(*) AS TRANSACTION_COUNT
FROM FRAUD_DATA
GROUP BY ISFRAUD;

-- 3. Transaction type distribution
SELECT
    TYPE,
    COUNT(*) AS TOTAL_COUNT
FROM FRAUD_DATA
GROUP BY TYPE
ORDER BY TOTAL_COUNT DESC;

-- 4. Fraud transactions by type
SELECT
    TYPE,
    COUNT(*) AS FRAUD_COUNT
FROM FRAUD_DATA
WHERE ISFRAUD = 1
GROUP BY TYPE
ORDER BY FRAUD_COUNT DESC;

-- 5. Average fraud transaction amount
SELECT
    TYPE,
    AVG(AMOUNT) AS AVG_FRAUD_AMOUNT,
    MAX(AMOUNT) AS MAX_FRAUD_AMOUNT
FROM FRAUD_DATA
WHERE ISFRAUD = 1
GROUP BY TYPE;
