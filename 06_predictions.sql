SELECT
    STEP,
    TYPE,
    AMOUNT,
    FRAUD_DB.PUBLIC.FRAUD_MODEL!PREDICT(
        INPUT_DATA => OBJECT_CONSTRUCT(
            'STEP', STEP,
            'TYPE', TYPE,
            'AMOUNT', AMOUNT,
            'OLD_BALANCE_ORIG', OLD_BALANCE_ORIG,
            'NEW_BALANCE_ORIG', NEW_BALANCE_ORIG,
            'OLD_BALANCE_DEST', OLD_BALANCE_DEST,
            'NEW_BALANCE_DEST', NEW_BALANCE_DEST
        )
    ) AS PREDICTION
FROM FRAUD_DB.PUBLIC.FRAUD_FEATURES
LIMIT 10;
